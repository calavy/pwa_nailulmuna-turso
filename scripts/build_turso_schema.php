<?php

declare(strict_types=1);

/**
 * Bangun migrations/turso/02_full_schema.sql dari DDL MySQL (tanpa INSERT/data).
 * CLI: php scripts/build_turso_schema.php
 */
$root = dirname(__DIR__);
$sources = [
    $root . '/impor_lokal_pwa_nailulmuna.sql',
    $root . '/migrasi_terbaru.sql',
];
$out = $root . '/migrations/turso/02_full_schema.sql';

$chunks = [];
$chunks[] = "-- Generated by scripts/build_turso_schema.php — review before apply to Turso prod\n";
$chunks[] = "PRAGMA foreign_keys = OFF;\n";

foreach ($sources as $file) {
    if (!is_file($file)) {
        fwrite(STDERR, "Skip missing: {$file}\n");
        continue;
    }
    $sql = file_get_contents($file);
    if (!is_string($sql)) {
        continue;
    }
    $sql = preg_replace('/^--.*$/m', '', $sql) ?? $sql;
    $sql = preg_replace('/\/\*.*?\*\//s', '', $sql) ?? $sql;
    $lines = preg_split('/\r\n|\n|\r/', $sql) ?: [];
    $buf = '';
    $inCreate = false;
    foreach ($lines as $line) {
        $trim = trim($line);
        if ($trim === '') {
            continue;
        }
        $upper = strtoupper($trim);
        if (str_starts_with($upper, 'INSERT ')
            || str_starts_with($upper, 'UPDATE ')
            || str_starts_with($upper, 'DELETE ')
            || str_starts_with($upper, 'USE ')
            || str_starts_with($upper, 'CREATE DATABASE')
            || str_starts_with($upper, 'SET NAMES')
            || str_starts_with($upper, 'SET FOREIGN_KEY')
        ) {
            continue;
        }
        if (str_starts_with($upper, 'CREATE TABLE')) {
            $inCreate = true;
            $buf = $line . "\n";
            continue;
        }
        if ($inCreate) {
            $buf .= $line . "\n";
            if (str_contains($trim, ';')) {
                $chunks[] = mysql_create_to_sqlite($buf) . "\n";
                $buf = '';
                $inCreate = false;
            }
            continue;
        }
        if (str_starts_with($upper, 'ALTER TABLE')) {
            $chunks[] = mysql_alter_to_sqlite($trim) . "\n";
        }
    }
}

$chunks[] = "PRAGMA foreign_keys = ON;\n";

file_put_contents($out, implode("\n", $chunks));
echo "Wrote {$out} (" . count($chunks) . " statements)\n";

function mysql_create_to_sqlite(string $create): string
{
    $s = $create;
    $s = preg_replace('/\s+ENGINE=\w+[^;]*/i', '', $s) ?? $s;
    $s = preg_replace('/\s+DEFAULT CHARSET=\w+/i', '', $s) ?? $s;
    $s = preg_replace('/\s+COLLATE=\w+/i', '', $s) ?? $s;
    $s = preg_replace('/\bINT\s+AUTO_INCREMENT\b/i', 'INTEGER', $s) ?? $s;
    $s = preg_replace('/\bBIGINT\s+AUTO_INCREMENT\b/i', 'INTEGER', $s) ?? $s;
    $s = preg_replace('/\bAUTO_INCREMENT\b/i', 'AUTOINCREMENT', $s) ?? $s;
    $s = preg_replace('/\bINT\b/i', 'INTEGER', $s) ?? $s;
    $s = preg_replace('/\bBIGINT\b/i', 'INTEGER', $s) ?? $s;
    $s = preg_replace('/\bTINYINT\s*\(\s*1\s*\)/i', 'INTEGER', $s) ?? $s;
    $s = preg_replace('/\bTINYINT\b/i', 'INTEGER', $s) ?? $s;
    $s = preg_replace('/\bENUM\s*\([^)]+\)/i', 'TEXT', $s) ?? $s;
    $s = preg_replace('/\bDECIMAL\s*\(\s*\d+\s*,\s*\d+\s*\)/i', 'REAL', $s) ?? $s;
    $s = preg_replace('/\bDATETIME\b/i', 'TEXT', $s) ?? $s;
    $s = preg_replace('/\bDATE\b/i', 'TEXT', $s) ?? $s;
    $s = preg_replace('/\bTIME\b/i', 'TEXT', $s) ?? $s;
    $s = preg_replace('/\bTIMESTAMP\b[^,\n)]+/i', "TEXT DEFAULT (datetime('now'))", $s) ?? $s;
    $s = preg_replace("/COMMENT\s+'[^']*'/i", '', $s) ?? $s;
    $s = preg_replace('/,\s*PRIMARY KEY\s*\(\s*id\s*\)/i', '', $s) ?? $s;
    $s = preg_replace('/\s+ON UPDATE CURRENT_TIMESTAMP/i', '', $s) ?? $s;
    $s = preg_replace('/,\s*(KEY|INDEX)\s+[^,\n]+/i', '', $s) ?? $s;
    $s = preg_replace('/,\s*UNIQUE KEY\s+[^,\n]+/i', '', $s) ?? $s;

    return trim($s);
}

function mysql_alter_to_sqlite(string $alter): string
{
    if (!preg_match('/ADD COLUMN IF NOT EXISTS/i', $alter)) {
        return '-- skip alter (review manual): ' . $alter;
    }
    $s = preg_replace('/\bINT\b/i', 'INTEGER', $alter) ?? $alter;
    $s = preg_replace('/\bTINYINT\s*\(\s*1\s*\)/i', 'INTEGER', $s) ?? $s;
    $s = preg_replace('/\bENUM\s*\([^)]+\)/i', 'TEXT', $s) ?? $s;
    $s = preg_replace('/\bVARCHAR\s*\(\s*\d+\s*\)/i', 'TEXT', $s) ?? $s;

    return $s;
}
