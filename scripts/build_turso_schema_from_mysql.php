<?php

declare(strict_types=1);

/**
 * Generate migrations/turso/02_full_schema.sql from live MySQL (SHOW CREATE TABLE).
 * CLI: php scripts/build_turso_schema_from_mysql.php
 */
$root = dirname(__DIR__);
require_once $root . '/helpers/pondok_db.php';
require_once $root . '/helpers/turso_schema_convert.php';

putenv('PONDOK_DB_DRIVER=mysql');
$local = $root . '/config/database.local.php';
if (!is_file($local)) {
    fwrite(STDERR, "Missing config/database.local.php\n");
    exit(1);
}
$cfg = require $local;
$pdo = pondok_db_connect(is_array($cfg) ? $cfg : [])['pdo'];
$dbName = (string) ($cfg['dbname'] ?? 'pwa_nailulmuna');

$st = $pdo->prepare(
    'SELECT table_name FROM information_schema.tables
     WHERE table_schema = ? AND table_type = ?
     ORDER BY table_name'
);
$st->execute([$dbName, 'BASE TABLE']);
$tables = $st->fetchAll(PDO::FETCH_COLUMN) ?: [];

$out = $root . '/migrations/turso/02_full_schema.sql';
$chunks = [];
$chunks[] = '-- Generated by scripts/build_turso_schema_from_mysql.php from live MySQL '
    . $dbName . ' (' . count($tables) . " tables)\n";
$chunks[] = 'PRAGMA foreign_keys = OFF;';
$allWarnings = [];
$seenTables = [];

foreach ($tables as $table) {
    $table = (string) $table;
    if (isset($seenTables[strtolower($table)])) {
        continue;
    }
    $seenTables[strtolower($table)] = true;
    $safe = str_replace('`', '``', $table);
    $row = $pdo->query('SHOW CREATE TABLE `' . $safe . '`')->fetch(PDO::FETCH_ASSOC);
    $ddl = (string) ($row['Create Table'] ?? '');
    if ($ddl === '') {
        $allWarnings[] = "empty DDL for {$table}";
        continue;
    }
    $converted = turso_convert_mysql_create_table($ddl);
    foreach ($converted['warnings'] as $w) {
        $allWarnings[] = $table . ': ' . $w;
    }
    if ($converted['create'] !== '') {
        $chunks[] = $converted['create'];
    }
    foreach ($converted['indexes'] as $idx) {
        $chunks[] = $idx;
    }
}

$chunks[] = 'PRAGMA foreign_keys = ON;';
$sql = implode("\n\n", $chunks) . "\n";
$issues = turso_validate_sqlite_schema_sql($sql);
if ($issues !== []) {
    fwrite(STDERR, "Validation warnings:\n- " . implode("\n- ", $issues) . "\n");
}

file_put_contents($out, $sql);
echo 'Wrote ' . $out . ' (' . count($seenTables) . " tables, " . count($chunks) . " chunks)\n";
if ($allWarnings !== []) {
    echo count($allWarnings) . " conversion warnings (see stderr)\n";
    foreach (array_slice($allWarnings, 0, 20) as $w) {
        fwrite(STDERR, "  {$w}\n");
    }
}
exit($issues !== [] ? 2 : 0);
